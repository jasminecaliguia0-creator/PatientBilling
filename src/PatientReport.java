    private void btnSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchActionPerformed
       if (txtPatientInitial.getText().trim().isEmpty()
        || txtFrom.getText().trim().isEmpty()
        || txtTo.getText().trim().isEmpty()) {

    JOptionPane.showMessageDialog(this, "Please fill out all fields.");
    return;
}

try {

    BufferedReader reader = new BufferedReader(new FileReader("patients.txt"));

    String line;
    DefaultTableModel model  = (DefaultTableModel) tblBillingHistory.getModel();

    model.setRowCount(0);

    String initial = txtPatientInitial.getText().trim().toLowerCase();

    String patientName = "";
    String admitDate = "";
    String dischargeDate = "";
    String roomRate = "";
    String doctorFee = "";
    String pharmacyFee = "";
    String total ="";

    while ((line = reader.readLine()) != null) {

        if (line.startsWith("Patient Name:")) {
            patientName = line.replace("Patient Name:", "").trim();
        }

        if (line.startsWith("Admit Date:")) {
            admitDate = line.replace("Admit Date:", "").trim();
        }

        if (line.startsWith("Discharge:")) {
            dischargeDate = line.replace("Discharge Date:", "").trim();
        }

        if (line.startsWith("Room Rate:")) {
            roomRate = line.replace("Room Rate:", "").trim();
        }

        if (line.startsWith("Doctor Fee:")) {
            doctorFee = line.replace("Doctor Fee:", "").trim();
        }

        if (line.startsWith("Pharmacy Fee:")) {

            pharmacyFee = line.replace("Pharmacy Fee:", "").trim();

            if (patientName.toLowerCase().startsWith(initial)) {

                model.addRow(new Object[]{
                    patientName,
                    admitDate,
                    dischargeDate,
                    roomRate,
                    doctorFee,
                    pharmacyFee,
                    "",
                    ""
                });
            }
        }
    }

    reader.close();

    if (model.getRowCount() == 0) {
        JOptionPane.showMessageDialog(this,
                "No matching patient found.");
    }

} catch (Exception e) {
    JOptionPane.showMessageDialog(this, e.getMessage());
}
    }//GEN-LAST:event_btnSearchActionPerformed

